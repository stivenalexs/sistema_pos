// Writes supabase/schema-snapshot.sql: the CURRENT schema of the local
// database (public and private), for reading only (D-076). Migrations stay
// the source of truth; this file answers "what does this function look like
// today?" without walking every migration that replaced it.
// Run after applying migrations: npm run db:snapshot (needs Docker).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "supabase/schema-snapshot.sql";

execFileSync("npx", ["supabase", "db", "dump", "--local", "--schema", "public,private", "--keep-comments", "-f", OUT], {
  stdio: "inherit",
  shell: process.platform === "win32",
});

// pg_dump wraps the file in \restrict / \unrestrict with a random key: drop
// them so the file only changes when the schema does.
const body = readFileSync(OUT, "utf8")
  .split(/\r?\n/)
  .filter((line) => !/^-- \\(un)?restrict /.test(line))
  .join("\n");

const header = [
  "-- GENERATED by `npm run db:snapshot` (scripts/db-snapshot.mjs, D-076). Do not edit.",
  "-- Current schema of the local database (public and private), for reading only.",
  "-- The migrations in supabase/migrations are the source of truth.",
  "",
].join("\n");

writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT}`);
