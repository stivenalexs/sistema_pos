-- Async actions: tracking table, pgmq queue and worker trigger (plan step 7, D-034).
--
-- Flow: an endpoint validates the user and calls enqueue_action() with the
-- secret key. The action row and the queue message are written in the same
-- transaction and the endpoint answers 202 with tracking_id (= actions.id).
-- pg_cron calls the worker endpoint every 10 seconds; the worker uses
-- claim_actions(), complete_action() and fail_action().
--
-- Forward-only migration. Undo with a new migration, never by editing this one.

create extension if not exists pgmq;
create extension if not exists pg_net;
create extension if not exists pg_cron with schema pg_catalog;

select pgmq.create('actions');

-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------

create type public.action_status as enum ('queued', 'processing', 'succeeded', 'failed');

create table public.actions (
  -- This id is the tracking_id returned to the client.
  id uuid primary key default gen_random_uuid(),
  -- Generated by the client once per intent (not per click).
  idempotency_key uuid not null,
  -- Valid types are defined by the handler registry in the code.
  type text not null check (type ~ '^[a-z][a-z0-9_]{1,62}$'),
  -- Null for system actions (webhooks, scheduled jobs).
  user_id uuid references auth.users (id) on delete set null,
  status public.action_status not null default 'queued',
  payload jsonb not null default '{}'::jsonb,
  result jsonb,
  error text,
  attempts integer not null default 0 check (attempts >= 0),
  max_attempts integer not null default 5 check (max_attempts between 1 and 20),
  queue_msg_id bigint,
  next_attempt_at timestamptz,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint actions_idempotency_key_key unique (idempotency_key)
);

create index actions_user_created_idx on public.actions (user_id, created_at desc);
-- For the "stuck queue" view of the admin panel (plan step 17).
create index actions_open_idx
  on public.actions (status, updated_at)
  where status in ('queued', 'processing');
create index actions_failed_idx
  on public.actions (finished_at desc)
  where status = 'failed';

create trigger set_updated_at before update on public.actions
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------------------
-- Privileges and RLS
-- ---------------------------------------------------------------------------

revoke all on public.actions from anon;
revoke insert, update, delete on public.actions from authenticated;

alter table public.actions enable row level security;

create policy "actions: read own"
  on public.actions for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "actions: admin reads all"
  on public.actions for select
  to authenticated
  using ((select private.has_staff_role(array['admin'])));

-- ---------------------------------------------------------------------------
-- Queue functions. Only the server (secret key / service_role) runs them.
-- ---------------------------------------------------------------------------

-- Seconds to wait before retry number n (1-based); the last value repeats.
create function private.action_backoff_seconds(p_attempt integer)
returns integer
language sql
immutable
set search_path = ''
as $$
  select (array[10, 30, 120, 600, 1800])[least(greatest(p_attempt, 1), 5)];
$$;

-- Saves the action and its queue message atomically. Repeating the call with
-- the same key returns the existing action (two tabs, network retries).
-- A key that belongs to another user or action type is rejected, so an
-- action is never revealed to someone else.
create function public.enqueue_action(
  p_idempotency_key uuid,
  p_type text,
  p_user_id uuid,
  p_payload jsonb default '{}'::jsonb,
  p_max_attempts integer default 5
)
returns table (tracking_id uuid, created boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_existing public.actions%rowtype;
  v_msg_id bigint;
begin
  insert into public.actions (idempotency_key, type, user_id, payload, max_attempts)
  values (p_idempotency_key, p_type, p_user_id, coalesce(p_payload, '{}'::jsonb), p_max_attempts)
  on conflict (idempotency_key) do nothing
  returning id into v_id;

  if v_id is not null then
    select pgmq.send('actions', jsonb_build_object('action_id', v_id)) into v_msg_id;
    update public.actions set queue_msg_id = v_msg_id where id = v_id;
    return query select v_id, true;
    return;
  end if;

  select * into v_existing
  from public.actions
  where idempotency_key = p_idempotency_key;

  if v_existing.user_id is distinct from p_user_id or v_existing.type <> p_type then
    raise exception 'idempotency_key_conflict'
      using errcode = 'P0001',
            hint = 'The key is already used by another action. Generate a new key for a new intent.';
  end if;

  return query select v_existing.id, false;
end;
$$;

-- Takes up to p_batch visible messages and marks their actions as processing.
-- A message stays invisible for p_visibility_seconds; if the worker dies, it
-- reappears and is claimed again (attempts keeps counting).
create function public.claim_actions(
  p_batch integer default 10,
  p_visibility_seconds integer default 60
)
returns table (
  action_id uuid,
  type text,
  user_id uuid,
  payload jsonb,
  attempt integer,
  max_attempts integer
)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_msg record;
  v_action public.actions%rowtype;
begin
  for v_msg in
    select * from pgmq.read('actions', p_visibility_seconds, p_batch)
  loop
    select * into v_action
    from public.actions a
    where a.id = (v_msg.message ->> 'action_id')::uuid
    for update;

    -- Orphan message or action already finished: drop the message.
    if v_action.id is null or v_action.status in ('succeeded', 'failed') then
      perform pgmq.archive('actions', v_msg.msg_id);
      continue;
    end if;

    -- The worker died on every previous attempt: give up.
    if v_action.attempts >= v_action.max_attempts then
      update public.actions
      set status = 'failed',
          error = coalesce(error, 'max_attempts_reached'),
          finished_at = now(),
          next_attempt_at = null
      where id = v_action.id;
      perform pgmq.archive('actions', v_msg.msg_id);
      continue;
    end if;

    update public.actions
    set status = 'processing',
        attempts = attempts + 1,
        started_at = now(),
        next_attempt_at = null,
        queue_msg_id = v_msg.msg_id
    where id = v_action.id;

    action_id := v_action.id;
    type := v_action.type;
    user_id := v_action.user_id;
    payload := v_action.payload;
    attempt := v_action.attempts + 1;
    max_attempts := v_action.max_attempts;
    return next;
  end loop;
end;
$$;

-- Marks a processing action as succeeded and removes its message.
create function public.complete_action(p_action_id uuid, p_result jsonb default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_msg_id bigint;
begin
  update public.actions
  set status = 'succeeded',
      result = p_result,
      error = null,
      finished_at = now(),
      next_attempt_at = null
  where id = p_action_id and status = 'processing'
  returning queue_msg_id into v_msg_id;

  if v_msg_id is not null then
    perform pgmq.archive('actions', v_msg_id);
  end if;
end;
$$;

-- Records a failure. Retries with backoff while attempts remain, unless the
-- error is permanent (for example, an unknown action type or invalid payload).
-- Returns the resulting status.
create function public.fail_action(
  p_action_id uuid,
  p_error text,
  p_permanent boolean default false
)
returns public.action_status
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_action public.actions%rowtype;
  v_delay integer;
begin
  select * into v_action
  from public.actions
  where id = p_action_id and status = 'processing'
  for update;

  if v_action.id is null then
    return null;
  end if;

  if p_permanent or v_action.attempts >= v_action.max_attempts then
    update public.actions
    set status = 'failed',
        error = left(p_error, 2000),
        finished_at = now(),
        next_attempt_at = null
    where id = p_action_id;
    if v_action.queue_msg_id is not null then
      perform pgmq.archive('actions', v_action.queue_msg_id);
    end if;
    return 'failed'::public.action_status;
  end if;

  v_delay := private.action_backoff_seconds(v_action.attempts);
  update public.actions
  set status = 'queued',
      error = left(p_error, 2000),
      next_attempt_at = now() + make_interval(secs => v_delay)
  where id = p_action_id;
  if v_action.queue_msg_id is not null then
    perform pgmq.set_vt('actions', v_action.queue_msg_id, v_delay);
  end if;
  return 'queued'::public.action_status;
end;
$$;

