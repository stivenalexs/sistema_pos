-- ---------------------------------------------------------------------------
-- Worker trigger
-- ---------------------------------------------------------------------------

-- Calls the worker endpoint when there are visible messages. The URL and the
-- shared secret live in Supabase Vault (names below) and are set per
-- environment; without them the job does nothing.
--   actions_worker_url     e.g. https://<host>/api/workers/actions
--   actions_worker_secret  same value as WORKER_SECRET in the app
create function private.invoke_actions_worker()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text;
  v_secret text;
begin
  select decrypted_secret into v_url
  from vault.decrypted_secrets where name = 'actions_worker_url';
  select decrypted_secret into v_secret
  from vault.decrypted_secrets where name = 'actions_worker_secret';

  if v_url is null or v_secret is null then
    return;
  end if;

  if not exists (select 1 from pgmq.q_actions where vt <= now()) then
    return;
  end if;

  perform net.http_post(
    url := v_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || v_secret
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 5000
  );
end;
$$;

revoke all on function private.invoke_actions_worker() from public;

select cron.schedule(
  'actions-worker',
  '10 seconds',
  'select private.invoke_actions_worker()'
);
